// Files cross between JavaScript and Rust as base64 text (see pack::encode_for_transport
// in Rust): Android can't deliver raw request bodies to commands, so one text-based
// path keeps Windows and Android identical.

/** Characters per step, small enough for String.fromCharCode's argument limit. */
const CHUNK = 0x8000;

export function bytesToBase64(bytes: Uint8Array): string {
  let binary = "";
  for (let i = 0; i < bytes.length; i += CHUNK) {
    binary += String.fromCharCode(...bytes.subarray(i, i + CHUNK));
  }
  return btoa(binary);
}

export function base64ToBytes(text: string): Uint8Array {
  const binary = atob(text);
  const bytes = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i++) {
    bytes[i] = binary.charCodeAt(i);
  }
  return bytes;
}
